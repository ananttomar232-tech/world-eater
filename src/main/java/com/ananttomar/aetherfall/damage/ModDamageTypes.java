package com.ananttomar.aetherfall.damage;

import com.ananttomar.aetherfall.AetherfallMod;
import net.minecraft.core.registries.Registries;
import net.minecraft.data.worldgen.BootstapContext;
import net.minecraft.resources.ResourceKey;
import net.minecraft.world.damagesource.DamageScaling;
import net.minecraft.world.damagesource.DamageSource;
import net.minecraft.world.damagesource.DamageType;
import net.minecraft.world.entity.Entity;
import net.minecraft.world.level.Level;
import org.jetbrains.annotations.Nullable;

/**
 * Data-driven damage types (1.20 damage system). Definitions are generated by datagen from {@link #bootstrap};
 * {@code death.attack.<message id>} keys in the language file give each its own death message.
 */
public final class ModDamageTypes {
    /** Claws, tail and wings of the World Eater. */
    public static final ResourceKey<DamageType> WORLD_EATER = key("world_eater");
    /** The Void Breath beam. */
    public static final ResourceKey<DamageType> VOID_BREATH = key("void_breath");
    /** Meteor impacts. */
    public static final ResourceKey<DamageType> VOID_METEOR = key("void_meteor");
    /** Dive slam and gravity well implosion shockwaves. */
    public static final ResourceKey<DamageType> VOID_SHOCKWAVE = key("void_shockwave");
    /** Erosion ticking at high stacks. Bypasses armor (tagged in datagen). */
    public static final ResourceKey<DamageType> EROSION = key("erosion");

    private ModDamageTypes() {
    }

    private static ResourceKey<DamageType> key(String name) {
        return ResourceKey.create(Registries.DAMAGE_TYPE, AetherfallMod.id(name));
    }

    public static void bootstrap(BootstapContext<DamageType> context) {
        context.register(WORLD_EATER, new DamageType("aetherfall.world_eater", DamageScaling.WHEN_CAUSED_BY_LIVING_NON_PLAYER, 0.1F));
        context.register(VOID_BREATH, new DamageType("aetherfall.void_breath", DamageScaling.WHEN_CAUSED_BY_LIVING_NON_PLAYER, 0.0F));
        context.register(VOID_METEOR, new DamageType("aetherfall.void_meteor", DamageScaling.WHEN_CAUSED_BY_LIVING_NON_PLAYER, 0.1F));
        context.register(VOID_SHOCKWAVE, new DamageType("aetherfall.void_shockwave", DamageScaling.WHEN_CAUSED_BY_LIVING_NON_PLAYER, 0.1F));
        context.register(EROSION, new DamageType("aetherfall.erosion", DamageScaling.NEVER, 0.0F));
    }

    public static DamageSource source(Level level, ResourceKey<DamageType> type, @Nullable Entity direct, @Nullable Entity causing) {
        return new DamageSource(level.registryAccess().registryOrThrow(Registries.DAMAGE_TYPE).getHolderOrThrow(type), direct, causing);
    }

    public static DamageSource source(Level level, ResourceKey<DamageType> type, @Nullable Entity attacker) {
        return source(level, type, attacker, attacker);
    }
}
